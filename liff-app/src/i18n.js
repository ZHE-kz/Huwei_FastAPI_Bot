export const translate = (language, key, values = {}) => {
  const message = messages[language]?.[key] ?? messages["zh-TW"][key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    message,
  );
};
